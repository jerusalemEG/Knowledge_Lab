# موسوعة بردية لندن وليدن السحرية الديموطيقية الكاملة
## (The Demotic Magical Papyrus of London and Leiden — BM 10070 & Leiden I 383)
### دراسة أركيولوجية وفيلولوجية وتحليلية شاملة لجميع الأعمدة (الوجه 1-29 والظهر 1-33) مع المعجم الصيدلاني ومقارنات النقد العقدي والابستمولوجي لأطروحة الدكتوراه

